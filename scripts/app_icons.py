"""Partner and console launcher icons from the Dahae logo (design/dahae-3d/out/appicon, see its render_all.py).

  python -I scripts/app_icons.py

Partner: the logo on an ink background (Android legacy + adaptive + themed, iOS, Windows).
Console: web icons only (it ships only as a web app). The customer icons come from the same renders (U1).
"""
import pathlib

from PIL import Image, ImageDraw

REPO = pathlib.Path(__file__).resolve().parents[1]
SRC = REPO / "design" / "dahae-3d" / "out" / "appicon"
APPS = REPO / "app" / "apps"
INK, LIGHT = "#17232C", "#EFF9FB"  # design/dahae-3d/scripts/post.py BG_INK / BG_LIGHT
LANCZOS = Image.Resampling.LANCZOS
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
ADAPTIVE_SAFE = 0.44  # 108 dp canvas, only the centred 66 dp circle is never masked
ICO_SIZES = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]


def logo(name):
    im = Image.open(SRC / name).convert("RGBA")
    return im.crop(im.getbbox())


def placed(mark, px, box, bg=None, radius=0.0):
    """Mark scaled into a centred box (fraction of the canvas) on a transparent, square or rounded canvas."""
    k = box * px / max(mark.size)
    m = mark.resize((max(1, round(mark.width * k)), max(1, round(mark.height * k))), LANCZOS)
    canvas = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    if bg:
        plate = Image.new("RGBA", (px, px), bg)
        mask = Image.new("L", (px, px), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, px - 1, px - 1), radius=round(radius * px), fill=255)
        canvas.paste(plate, mask=mask)
    canvas.alpha_composite(m, ((px - m.width) // 2, (px - m.height) // 2))
    return canvas


def save(im, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, optimize=True)


def partner(flat, mono):
    app = APPS / "partner"
    res = app / "android" / "app" / "src" / "main" / "res"
    for d, k in DENSITIES.items():
        save(placed(flat, round(48 * k), 0.7, INK, radius=0.2), res / f"mipmap-{d}" / "ic_launcher.png")
        save(placed(flat, round(108 * k), ADAPTIVE_SAFE), res / f"mipmap-{d}" / "ic_launcher_foreground.png")
        save(placed(mono, round(108 * k), ADAPTIVE_SAFE), res / f"mipmap-{d}" / "ic_launcher_monochrome.png")
    (res / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (res / "mipmap-anydpi-v26" / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Adaptive icon (Android 8+); monochrome layer = themed icon (Android 13+). Generated by scripts/app_icons.py. -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n", encoding="utf-8", newline="\n")
    (res / "values" / "colors.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{INK}</color>\n</resources>\n', encoding="utf-8", newline="\n")
    # iOS: opaque (App Store rejects alpha), full bleed; iOS applies its own corner mask.
    ios = app / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset"
    for png in ios.glob("*.png"):
        px = Image.open(png).size[0]
        save(placed(flat, px, 0.6, INK).convert("RGB"), png)
    ico = placed(flat, 256, 0.7, INK, radius=0.2)
    ico.save(app / "windows" / "runner" / "resources" / "app_icon.ico", sizes=ICO_SIZES)


def console(flat):
    web = APPS / "console" / "web"
    save(placed(flat, 32, 0.86), web / "favicon.png")
    for px in (192, 512):
        save(placed(flat, px, 0.56, LIGHT).convert("RGB"), web / "icons" / f"Icon-{px}.png")
        # Maskable: keep the mark inside the 80% safe circle.
        save(placed(flat, px, 0.5, LIGHT).convert("RGB"), web / "icons" / f"Icon-maskable-{px}.png")


def main():
    flat, mono = logo("logo_flat_1024.png"), logo("logo_mono_1024.png")
    partner(flat, mono)
    console(flat)
    ios = APPS / "partner" / "ios" / "Runner" / "Assets.xcassets" / "AppIcon.appiconset"
    assert all(Image.open(p).mode == "RGB" for p in ios.glob("*.png")), "iOS icons must be opaque"
    print("app icons: partner + console written")


if __name__ == "__main__":
    main()
